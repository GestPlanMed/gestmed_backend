async function main() {
  const uniqueNames = Array.from(new Set(examTypes.map(name => name.trim())))
  
  for (const name of uniqueNames) {
    if (!name) continue
    await prisma.examType.upsert({
      where: { name },
      update: {},
      create: { name },
    })
  }

  console.log(`Inseridos ${uniqueNames.length} tipos de exames.`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
